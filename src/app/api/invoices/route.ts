import { NextResponse } from "next/server";
import { PDFDocument, StandardFonts } from "pdf-lib";
import { z } from "zod";
import { apiError } from "@/lib/http";
import { DomainError } from "@/lib/db";
import { session, sameOrigin, rateLimit } from "@/lib/session";
import { invoiceAction, requestInvoice } from "@/lib/providers/invoicing";
export async function GET(request: Request) {
  try {
    const w = await session();
    const url = new URL(request.url);
    const invoice = requestInvoice(
      w,
      z.string().min(1).parse(url.searchParams.get("requestId")),
    );
    if (url.searchParams.get("format") !== "pdf")
      return NextResponse.json(
        { invoice },
        { headers: { "Cache-Control": "private, no-store" } },
      );
    if (!invoice?.snapshot)
      throw new DomainError(
        "Refresh a verified PayPal invoice before downloading.",
      );
    const data = JSON.parse(invoice.snapshot);
    const pdf = await PDFDocument.create();
    const page = pdf.addPage([595, 842]);
    const font = await pdf.embedFont(StandardFonts.Helvetica);
    const lines = [
      "PAYPAL SANDBOX INVOICE — DRAFT RECORD",
      `PayPal invoice ID: ${invoice.provider_id}`,
      `Invoice number: ${invoice.invoice_number}`,
      `Provider status: ${invoice.status}`,
      `Recipient: ${invoice.recipient_email}`,
      `Verified at: ${invoice.updated_at}`,
      "",
      ...data.items.flatMap((i: any) => [
        i.name,
        i.description || "",
        `Quantity: ${i.quantity} | Amount: ${i.unit_amount.value} ${i.unit_amount.currency_code}`,
      ]),
      "",
      `Total: ${data.amount.value} ${data.amount.currency_code}`,
      "",
      "Generated by ProcureProof from verified PayPal invoice data.",
      "Not a PayPal-issued PDF, tax invoice or proof of payment.",
      "Draft invoices are not sent. Checkout collects payment separately.",
    ];
    let y = 790;
    for (const line of lines) {
      const clean = String(line).replace(/[^\x20-\x7E]/g, " ");
      for (const chunk of clean.match(/.{1,85}(?:\s|$)|.{1,85}/g) || [""]) {
        page.drawText(chunk.trim(), { x: 40, y, size: 10, font });
        y -= 18;
      }
    }
    return new NextResponse(Buffer.from(await pdf.save()), {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="${invoice.invoice_number}.pdf"`,
        "Cache-Control": "private, no-store",
      },
    });
  } catch (e) {
    return apiError(e);
  }
}
export async function POST(request: Request) {
  try {
    sameOrigin(request);
    const w = await session();
    rateLimit(`invoice:${w.id}`, 20);
    const input = z
      .object({
        requestId: z.string(),
        action: z.enum(["create", "refresh"]),
        email: z.email().optional(),
      })
      .parse(await request.json());
    return NextResponse.json({
      invoice: await invoiceAction(
        w,
        input.requestId,
        input.action,
        input.email,
      ),
    });
  } catch (e) {
    return apiError(e);
  }
}
